#!/usr/bin/env python3
"""Tiny HTTP server for the static factor dashboard.

Serves data/factor_dashboard.html (regenerated by entrypoint.sh loop) at /
with no-cache headers so a browser refresh always sees the latest snapshot.
"""
from __future__ import annotations

import os
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HTML_PATH = Path(os.environ.get("DASHBOARD_HTML", "/app/data/factor_dashboard.html"))


class DashboardHandler(SimpleHTTPRequestHandler):
    _PATHS = ("/", "/index.html", "/factor_dashboard.html")

    def _send_head_or_body(self, head_only: bool) -> None:  # noqa: N802
        if self.path not in self._PATHS:
            self.send_error(404, "dashboard is served at /")
            return
        try:
            body = HTML_PATH.read_bytes()
        except OSError:
            self.send_error(503, "dashboard not generated yet, retry shortly")
            return
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Last-Modified",
                         self.date_time_string(HTML_PATH.stat().st_mtime))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        if not head_only:
            self.wfile.write(body)

    def do_GET(self) -> None:  # noqa: N802
        self._send_head_or_body(head_only=False)

    def do_HEAD(self) -> None:  # noqa: N802
        # 前端自动刷新轮询用：与 GET 同路径约束，仅返回头（含 Last-Modified）
        self._send_head_or_body(head_only=True)

    def log_message(self, fmt: str, *args: object) -> None:
        print(f"[http] {self.address_string()} {fmt % args}", flush=True)


def main() -> None:
    port = int(os.environ.get("DASHBOARD_PORT", "8765"))
    server = ThreadingHTTPServer(("0.0.0.0", port), DashboardHandler)
    print(f"[http] serving {HTML_PATH} on 0.0.0.0:{port}", flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
